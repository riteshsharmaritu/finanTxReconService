CREATE TABLE IF NOT EXISTS transactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_id           VARCHAR(255)   NOT NULL,
    amount          NUMERIC(19, 4) NOT NULL,
    txn_timestamp   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    from_account    VARCHAR(255)   NOT NULL,
    to_account      VARCHAR(255)   NOT NULL,
    merchant        VARCHAR(255),
    idempotency_key VARCHAR(255),
    anomaly         BOOLEAN        NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_transactions_tx_id UNIQUE (tx_id),
    CONSTRAINT uk_transactions_idempotency_key UNIQUE (idempotency_key)
);

CREATE INDEX IF NOT EXISTS idx_transactions_from_account ON transactions (from_account);
CREATE INDEX IF NOT EXISTS idx_transactions_to_account ON transactions (to_account);
CREATE INDEX IF NOT EXISTS idx_transactions_txn_timestamp ON transactions (txn_timestamp);
CREATE INDEX IF NOT EXISTS idx_transactions_merchant ON transactions (merchant);
